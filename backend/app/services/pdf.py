"""PDF documents: wallet statements and transaction / payment receipts (reportlab, no external services).

While live payments are disabled every page carries a diagonal "SANDBOX — NOT A REAL PAYMENT" watermark so a
simulated document can never pass as a real one.
"""

from __future__ import annotations

import io
from datetime import datetime, timedelta
from decimal import Decimal

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.core.config import settings
from app.core.money import to_api_str

BRAND = colors.HexColor("#065f46")
INK = colors.HexColor("#0b1220")
MUTED = colors.HexColor("#64748b")
_styles = getSampleStyleSheet()
H1 = ParagraphStyle("h1", parent=_styles["Heading1"], textColor=BRAND, fontSize=18, spaceAfter=2)
SMALL = ParagraphStyle("small", parent=_styles["Normal"], fontSize=8, textColor=MUTED)
AMOUNT = ParagraphStyle("amount", parent=_styles["Normal"], fontName="Helvetica-Bold", fontSize=22, leading=28,
                        textColor=INK)
BODY = ParagraphStyle("body", parent=_styles["Normal"], fontSize=9, textColor=INK, leading=11)


def ghs(v: Decimal | str | None, currency: str = "GHS") -> str:
    if v is None or v == "":
        return ""
    s = to_api_str(Decimal(str(v)))
    neg = s.startswith("-")
    whole, _, frac = s.lstrip("-").partition(".")
    return f"{'-' if neg else ''}{currency} {int(whole):,}.{(frac + '00')[:max(2, len(frac))]}"


def _decorate(canvas, doc, title: str) -> None:
    canvas.saveState()
    w, h = A4
    canvas.setFillColor(BRAND)
    canvas.rect(0, h - 14 * mm, w, 14 * mm, fill=1, stroke=0)
    canvas.setFillColor(colors.white)
    canvas.setFont("Helvetica-Bold", 13)
    canvas.drawString(15 * mm, h - 9.5 * mm, "FinCore")
    canvas.setFont("Helvetica", 9)
    canvas.drawRightString(w - 15 * mm, h - 9.5 * mm, title)
    canvas.setFillColor(MUTED)
    canvas.setFont("Helvetica", 7.5)
    canvas.drawString(15 * mm, 10 * mm, f"Generated by FinCore on {datetime.now():%d %b %Y %H:%M} UTC. "
                                        "Figures come from FinCore's double-entry ledger.")
    canvas.drawRightString(w - 15 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


class _Doc(SimpleDocTemplate):
    """Draws the sandbox watermark *after* page content so tables can't hide it."""

    simulated = False

    def afterPage(self):  # noqa: N802 (reportlab hook name)
        if not self.simulated:
            return
        c = self.canv
        w, h = A4
        c.saveState()
        c.setFillColor(colors.Color(0.85, 0.6, 0.0, alpha=0.16))
        c.setFont("Helvetica-Bold", 30)
        c.translate(w / 2, h / 2)
        c.rotate(35)
        c.drawCentredString(0, 0, "SANDBOX — NOT A REAL PAYMENT")
        c.restoreState()


def _build(title: str, story: list, simulated: bool) -> bytes:
    buf = io.BytesIO()
    doc = _Doc(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=22 * mm,
                            bottomMargin=18 * mm, title=title, author="FinCore")
    doc.simulated = simulated
    deco = lambda c, d: _decorate(c, d, title)  # noqa: E731
    doc.build(story, onFirstPage=deco, onLaterPages=deco)
    return buf.getvalue()


def _kv_table(rows: list[tuple[str, str]]) -> Table:
    t = Table([[Paragraph(k, SMALL), Paragraph(v or "—", BODY)] for k, v in rows], colWidths=[45 * mm, 125 * mm])
    t.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                           ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#e2e8f0"))]))
    return t


def statement_pdf(data: dict, account_name: str) -> bytes:
    cur = data["currency"]
    end_inclusive = data["period_end"] - timedelta(days=1)
    story = [
        Paragraph("Account statement", H1),
        Paragraph(f"{account_name} · Account {data['account_number']} · {cur}", BODY),
        Paragraph(f"Period {data['period_start']:%d %b %Y} – {end_inclusive:%d %b %Y} ", SMALL),
        Spacer(1, 6 * mm),
    ]
    summary = Table([["Opening balance", "Money in", "Money out", "Closing balance"],
                     [ghs(data["opening_balance"], cur), ghs(data["total_credits"], cur),
                      ghs(data["total_debits"], cur), ghs(data["closing_balance"], cur)]],
                    colWidths=[42.5 * mm] * 4)
    summary.setStyle(TableStyle([
        ("FONT", (0, 0), (-1, 0), "Helvetica", 8), ("TEXTCOLOR", (0, 0), (-1, 0), MUTED),
        ("FONT", (0, 1), (-1, 1), "Helvetica-Bold", 11), ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f1f5f9")),
        ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5)]))
    story += [summary, Spacer(1, 6 * mm)]
    rows = [["Date", "Description", "Reference", "Debit", "Credit", "Balance"]]
    for ln in data["lines"]:
        rows.append([f"{ln['date']:%d %b %Y}", Paragraph(str(ln["description"])[:90], BODY),
                     Paragraph(ln["reference"], SMALL),
                     ghs(ln["debit"], cur) if ln["debit"] else "", ghs(ln["credit"], cur) if ln["credit"] else "",
                     ghs(ln["balance"], cur)])
    if len(rows) == 1:
        rows.append(["", Paragraph("No transactions in this period.", BODY), "", "", "", ""])
    t = Table(rows, colWidths=[20 * mm, 55 * mm, 35 * mm, 20 * mm, 20 * mm, 22 * mm], repeatRows=1)
    t.setStyle(TableStyle([
        ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 8), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("BACKGROUND", (0, 0), (-1, 0), BRAND), ("FONT", (0, 1), (-1, -1), "Helvetica", 8),
        ("ALIGN", (3, 0), (-1, -1), "RIGHT"), ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f8fafc")]),
        ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#e2e8f0"))]))
    story.append(t)
    return _build("Account statement", story, simulated=not settings.live_payments_enabled)


def receipt_pdf(title: str, amount: Decimal, currency: str, status: str, rows: list[tuple[str, str]],
                simulated: bool) -> bytes:
    story = [
        Paragraph(title, H1),
        Paragraph(ghs(amount, currency), AMOUNT),
        Spacer(1, 3 * mm),
        Paragraph(f"Status: <b>{status.replace('_', ' ').title()}</b>"
                  + (" · <font color='#b45309'>Simulated (sandbox) — no real money moved</font>" if simulated else ""),
                  BODY),
        Spacer(1, 6 * mm),
        _kv_table(rows),
    ]
    return _build(title, story, simulated=simulated)


def payer_fee(t, is_sender: bool) -> Decimal:
    """Fee the viewer actually paid. Merchant payment fees (MDR) are charged to the merchant, not the customer."""
    if t.type == "payment" and is_sender:
        return Decimal("0")
    if not is_sender and t.type in ("transfer", "withdrawal"):
        return Decimal("0")  # the sender paid it
    return t.fee


def transaction_receipt(t, wallet_ids: set) -> bytes:
    cp = t.counterparty or {}
    direction = "Received" if t.destination_wallet_id in wallet_ids and t.source_wallet_id not in wallet_ids else "Sent"
    party = cp.get("name") or cp.get("merchant") or cp.get("label") or cp.get("account_number") or cp.get("msisdn")
    rows = [("Reference", t.reference), ("Type", t.type.replace("_", " ").title()), ("Direction", direction),
            ("Description", t.description), ("Counterparty", party), ("Channel", t.channel.replace("_", " ").title()),
            ("Fee", ghs(payer_fee(t, direction == "Sent"), t.currency)), ("Date", f"{t.created_at:%d %b %Y %H:%M} UTC"),
            ("Completed", f"{t.completed_at:%d %b %Y %H:%M} UTC" if t.completed_at else "—")]
    if t.provider_reference:
        rows.append(("Provider reference", t.provider_reference))
    if t.failure_reason:
        rows.append(("Failure reason", t.failure_reason))
    return receipt_pdf("Transaction receipt", t.amount, t.currency, t.status, rows,
                       simulated=t.provider_mode == "sandbox" or not settings.live_payments_enabled)


def payment_receipt(pr, merchant_name: str, merchant_code: str, *, mask_customer: bool) -> bytes:
    email = pr.customer_email or ""
    if mask_customer and "@" in email:
        name, domain = email.split("@", 1)
        email = f"{name[:2]}***@{domain}"
    rows = [("Merchant", f"{merchant_name} ({merchant_code})"), ("Reference", pr.reference),
            ("Merchant reference", pr.merchant_reference or "—"), ("Description", pr.description or "—"),
            ("Customer", pr.customer_name or email or "—"),
            ("Paid with", (pr.network or pr.channel or "—").replace("_", " ").upper() if pr.network else
             (pr.channel or "—").replace("_", " ").title()),
            ("Paid at", f"{pr.paid_at:%d %b %Y %H:%M} UTC" if pr.paid_at else "—")]
    if not mask_customer:
        rows += [("Fee", ghs(pr.fee, pr.currency)), ("Refunded", ghs(pr.amount_refunded, pr.currency))]
    return receipt_pdf("Payment receipt", pr.amount, pr.currency, pr.status, rows,
                       simulated=pr.environment != "live" or not settings.live_payments_enabled)
